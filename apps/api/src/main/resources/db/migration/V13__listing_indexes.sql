-- Performance of the listings, part 2. Runs outside a transaction (V13__listing_indexes.sql.conf)
-- because CREATE/DROP INDEX CONCURRENTLY does not block the inserts every request makes into
-- audit_event. Every statement is idempotent: after a failure, drop any index left INVALID
-- (docs/performance.md shows the query), run `flyway repair` and start the application again.

-- Primary key (id, occurred_at): a partitioned table must include the partition key in its unique
-- constraints, so the trail can be partitioned by month later without rebuilding this index. Ids
-- are UUIDv7 (time ordered) and generated by the API, so id alone stays unique in practice.
CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS audit_event_id_occurred_at_key ON audit_event (id, occurred_at);
-- The swap needs a moment of exclusive lock. Behind a long transaction it would queue every audit
-- insert while it waits; give up instead, and the migration can simply be run again.
SET lock_timeout = '5s';
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
               WHERE c.relname = 'audit_event_pkey' AND i.indnatts = 1) THEN
        ALTER TABLE audit_event DROP CONSTRAINT audit_event_pkey;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'audit_event_pkey') THEN
        ALTER TABLE audit_event ADD CONSTRAINT audit_event_pkey PRIMARY KEY USING INDEX audit_event_id_occurred_at_key;
    END IF;
END $$;
RESET lock_timeout;
-- The swap renames the index to audit_event_pkey. When this script runs again after a failure
-- further down, the first statement builds the index once more; drop that redundant copy.
DROP INDEX CONCURRENTLY IF EXISTS audit_event_id_occurred_at_key;

-- Newest first is the order of every audit query. The tie-breaker runs in the same direction, so
-- one index serves both the ORDER BY and the "events before this one" cursor.
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_event_occurred_at_id_idx ON audit_event (occurred_at DESC, id DESC);
DROP INDEX CONCURRENTLY IF EXISTS audit_event_occurred_at_idx;

-- Filtered listings: the filter column first, then the time, so the newest matching rows come
-- straight from the index instead of being collected and sorted. The id is left out: two events of
-- one person in the same microsecond are rare and cheap to order, and it would add 16 bytes a row.
-- Entities by id alone (ids are UUIDs, unique across types): it also serves the account page,
-- which asks by id without the type.
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_event_actor_idx
    ON audit_event (actor_id, occurred_at DESC) WHERE actor_id IS NOT NULL;
DROP INDEX CONCURRENTLY IF EXISTS audit_event_actor_id_idx;
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_event_entity_occurred_idx
    ON audit_event (entity_id, occurred_at DESC) WHERE entity_id IS NOT NULL;
DROP INDEX CONCURRENTLY IF EXISTS audit_event_entity_idx;

-- Action filter is a prefix (iam.user matches iam.user.*): pattern ops let LIKE 'x%' use the index.
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_event_action_idx ON audit_event (action text_pattern_ops);
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_event_correlation_idx
    ON audit_event (correlation_id) WHERE correlation_id IS NOT NULL;

-- "Who" contains: trigram index on the same expression the query uses, lower(actor_email).
CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_event_actor_email_trgm_idx
    ON audit_event USING gin (lower(actor_email) gin_trgm_ops);

-- Tasks: the default order of the listing (open first, then due date, undated last), and the
-- text search in title and description.
CREATE INDEX CONCURRENTLY IF NOT EXISTS tasks_listing_idx
    ON tasks (status DESC, due_date ASC NULLS LAST, created_at, id);
DROP INDEX CONCURRENTLY IF EXISTS tasks_status_due_date_idx;
CREATE INDEX CONCURRENTLY IF NOT EXISTS tasks_title_trgm_idx ON tasks USING gin (lower(title) gin_trgm_ops);
CREATE INDEX CONCURRENTLY IF NOT EXISTS tasks_description_trgm_idx ON tasks USING gin (lower(description) gin_trgm_ops);
